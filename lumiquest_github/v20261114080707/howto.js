let openCard = null;
const el = (tag, cls, text) => { const n = document.createElement(tag); if (cls) n.className = cls; if (text != null) n.textContent = text; return n; };

/** Відкрити картку «Як грати» для ключа key. Повертає Promise, що завершується при закритті. */
export function open(key, app) {
  const d = RAW[key];
  if (!d) return Promise.resolve();
  if (openCard) openCard.close();
  const U = UI_STR[L()];
  const l = L();
  pauseGame(true);
  return new Promise((resolve) => {
    const ov = el('div', 'ht-ov');
    ov.setAttribute('role', 'dialog'); ov.setAttribute('aria-modal', 'true');
    const card = el('div', 'ht-card');
    const head = el('div', 'ht-head');
    head.append(el('span', 'ht-ico', d.emoji), el('div', 'ht-ttl'));
    head.lastChild.append(el('small', 'ht-how', U.how), el('b', 'ht-name', d.title[l] || d.title.uk));
    const list = el('ol', 'ht-steps');
    const rows = d.steps.map((s, i) => {
      const li = el('li', 'ht-step');
      li.style.setProperty('--i', i);
      const pic = el('div', `ht-pic ht-g-${s.g}`);
      pic.append(el('span', 'ht-emo', s.e));
      pic.append(el('span', 'ht-num', `${i + 1}`));
      if (s.g !== 'look') pic.append(el('span', 'ht-hand', '👆'));
      else pic.append(el('span', 'ht-eye', '👀'));
      const body = el('div', 'ht-txt');
      body.append(el('p', 'ht-p', txt(s, app)));
      li.append(pic, body);
      list.append(li);
      return li;
    });
    const btns = el('div', 'ht-btns');
    const again = el('button', 'ht-btn ht-again', U.again); again.type = 'button';
    const go = el('button', 'ht-btn ht-go', U.go); go.type = 'button';
    btns.append(again, go);
    card.append(head, list, btns);
    ov.append(card);
    document.body.append(ov);
    requestAnimationFrame(() => ov.classList.add('is-on'));

    let token = 0;
    const stopVoice = () => { token++; try { const s = ss(); if (s && (s.speaking || s.pending)) s.cancel(); } catch (e) { /* */ } rows.forEach((r) => r.classList.remove('is-say')); };
    const read = async () => {
      stopVoice();
      const my = token;
      const soundOn = !A || !A.getSettings || A.getSettings().sound !== false;
      await waitVoices();
      const v = soundOn ? voiceFor(l) : null;
      if (!v) { again.hidden = true; return; }   // голосу немає — тихо, кнопку ховаємо
      try { A?.duck?.(true); } catch (e) { /* */ }
      for (let i = 0; i < d.steps.length; i++) {
        if (my !== token) break;
        rows.forEach((r, j) => r.classList.toggle('is-say', j === i));
        await sayOne(txt(d.steps[i], app), v);
      }
      if (my === token) rows.forEach((r) => r.classList.remove('is-say'));
      try { A?.duck?.(false); } catch (e) { /* */ }
    };
    const close = () => {
      if (!openCard || openCard.ov !== ov) return;
      openCard = null;
      stopVoice();
      try { A?.duck?.(false); } catch (e) { /* */ }
      document.removeEventListener('keydown', onKey, true);
      ov.classList.remove('is-on');
      setTimeout(() => ov.remove(), 260);
      pauseGame(false);
      resolve();
    };
    const onKey = (e) => { if (e.key === 'Escape' || e.key === 'Enter') { e.preventDefault(); e.stopPropagation(); close(); } };
    document.addEventListener('keydown', onKey, true);
    again.onclick = () => { try { app?.tg?.tap?.('light'); } catch (e) { /* */ } read(); };
    go.onclick = () => { try { app?.tg?.tap?.('medium'); } catch (e) { /* */ } close(); };
    ov.addEventListener('pointerdown', (e) => e.stopPropagation());
    openCard = { ov, close };
    setTimeout(read, 350);
  });
}

// Пауза гри «якщо можливо»: ігри з canvas/rAF ставлять себе на паузу на visibilitychange (document.hidden).
let hiddenFake = false;
function pauseGame(on) {
  try {
    if (on && !hiddenFake) {
      Object.defineProperty(document, 'hidden', { configurable: true, get: () => true });
      hiddenFake = true;
      document.dispatchEvent(new Event('visibilitychange'));
      delete document.hidden; hiddenFake = false;   // повертаємо справжнє значення одразу після сповіщення
      if (!document.hidden) document.documentElement.classList.remove('lq-hidden');   // app.js глушить CSS-анімації — картці вони потрібні
    } else if (!on) {
      document.dispatchEvent(new Event('visibilitychange'));
    }
  } catch (e) { hiddenFake = false; }
}

/** Хук роутера: кнопка «❓» на ігровому екрані + автопоказ при першому запуску типу гри. */
export function attach(root, name, params, app) {
  const key = keyFor(name, params);
  if (!key || !root || !root.isConnected) return;
  const U = UI_STR[L()];
  const b = el('button', 'ht-fab', '❓');
  b.type = 'button';
  b.setAttribute('aria-label', U.help); b.title = U.help;
  b.addEventListener('click', (e) => { e.stopPropagation(); try { app?.tg?.tap?.('light'); } catch (er) { /* */ } open(key, app); });
  b.addEventListener('pointerdown', (e) => e.stopPropagation());
  root.append(b);
  const st = app && app.state;
  if (st && !(st.howto_seen && st.howto_seen[key])) {
    st.howto_seen = st.howto_seen || {};
    st.howto_seen[key] = true;
    try { app.save(); } catch (e) { /* */ }
    setTimeout(() => { if (root.isConnected && !root.classList.contains('is-leaving')) open(key, app); }, 420);
  }
}
